package jp.co.trainocate.answer.form;

public class UserForm {
	private int id;
	private String password;
	
	//～～Getter&Setterメソッド～～
	
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public String getPassword() {
		return password;
	}
	public void setPassword(String password) {
		this.password = password;
	}
	
	
}
